import { atom } from "jotai"
import { logOutAtom, userSecureAtom } from "./auth-store"
import { MINIMUM_SHORT_ANSWER_LENGTH, WS_BASE_URL } from "@/src/utils/constants"
import { createPostSocketAtom } from "./socket-store"
import { refreshAccessToken } from "@/src/utils/refresh-access-token"
import io from "socket.io-client"
import { currPageAtom, pageCountAtom } from "./pager-store"
import { router } from "expo-router"
import { Alert } from "react-native"
import * as ImagePicker from "expo-image-picker"
import { QnaType, Question } from "@/src/types/question.types"
import { atomWithStorage, createJSONStorage } from "jotai/utils"
import AsyncStorage from "@react-native-async-storage/async-storage"
import { ImageObject } from "@/src/types/image-object.type"
import { queryClientAtom } from "./general-store"
import { LocationType } from "@/src/types/location.type"

/**
 * How things work:
 * We have a starting page question DEFAULT_QUESTION set below. We don't grab the question from
 * backend, since I don't want a separate call for it. If we decide it's not consistent, we can
 * change it at any time, by adding a get-first-question or something similar.
 *
 * Then we have the generated questions, which the user can request to get a different question.
 * Questions are generated by emitting "chat", then listening for "question"
 *
 * The location page and last page are next. Last page contains hardcoded questions in the frontend.
 * We ask for the title, description, optional images, and some other settings about the post.
 */

export const INITIAL_PAGE_COUNT = 3 // Starting page + location page + last page
const DEFAULT_PUBLIC_POST = true

const DEFAULT_QUESTION: Question = {
  type: "short_answer",
  question: "Start by describing what you are looking for.",
}

const settings = {
  title: "",
  description: "",
  images: [] as ImageObject[],
  publicPost: DEFAULT_PUBLIC_POST,
  location: null as LocationType,
  distance: 5_000,
  zoom: 12,
}
export const settingsAtom = atomWithStorage(
  "post-settings",
  settings,
  createJSONStorage(() => AsyncStorage),
  {
    getOnInit: true,
  }
)

export const qnaAtom = atom<QnaType>([{ question: DEFAULT_QUESTION, answer: [] }])
export const loadingAtom = atom(false)
export const publicPostAtom = atom(DEFAULT_PUBLIC_POST)
export const imagesAtom = atom<ImageObject[]>([])
export const editedAtom = atom(false)

export const initCreatePostAtom = atom(null, async (get, set) => {
  const user = await get(userSecureAtom)
  if (!user) return
  const currSocket = get(createPostSocketAtom)
  if (currSocket && (currSocket.connected || get(loadingAtom))) return

  set(loadingAtom, true)

  const socket = io(WS_BASE_URL + "/create-post", {
    auth: {
      token: user.accessToken,
    },
    transports: ["websocket", "polling"],
  })

  set(createPostSocketAtom, socket)

  socket.io.on("reconnect_failed", () => {
    set(loadingAtom, false)
  })

  socket.on("connect", () => {
    console.log("Connected to WebSocket server for create-post")
    set(loadingAtom, false)
    set(pageCountAtom, INITIAL_PAGE_COUNT)
  })

  socket.on("disconnect", () => {
    console.log("Disconnected from WebSocket server for create-post")
  })

  socket.on("error", (err: any) => {
    console.error("WebSocket error event:", err)
    set(loadingAtom, false)
    Alert.alert("Connection Error", "An error occurred with the connection. Please try again.")
  })

  socket.on("connect_error", async () => {
    const accessToken = await refreshAccessToken(user.refreshToken)
    if (accessToken === null) {
      set(logOutAtom)
      return
    }
    await set(userSecureAtom, { ...user, accessToken })
    socket.io.opts.auth = { token: accessToken }
    socket.connect()
  })

  socket.on("draft-saved", () => {
    // If on first page, invalidate my-posts to show the new draft
    if (get(currPageAtom) <= 1) {
      get(queryClientAtom).invalidateQueries({ queryKey: ["my-posts"] })
    }
  })

  socket.on("ai-title-generated", async (title: string) => {
    const prevSettings = await get(settingsAtom)
    await set(settingsAtom, { ...prevSettings, title })
    set(loadingAtom, false)
  })

  socket.on("question", (qna: QnaType) => {
    set(qnaAtom, qna)
    set(loadingAtom, false)
    set(currPageAtom, curr => curr + 1)
    set(pageCountAtom, qna.length + INITIAL_PAGE_COUNT - 1) // -1 because the first question is already counted in INITIAL_PAGE_COUNT
  })

  socket.on("draft-restored", (qna: QnaType) => {
    set(qnaAtom, qna)
    set(pageCountAtom, qna.length + INITIAL_PAGE_COUNT - 1) // -1 because the first question is already counted in INITIAL_PAGE_COUNT

    // Navigate to the first unanswered question, or to the last page if all answered
    const firstUnansweredIdx = qna.findIndex(item => item.answer.length === 0)
    if (firstUnansweredIdx !== -1) {
      set(currPageAtom, firstUnansweredIdx)
    } else {
      set(currPageAtom, qna.length)
    }

    set(loadingAtom, false)
  })

  socket.on("chat-finished", () => {
    set(currPageAtom, curr => curr + 1)
    set(loadingAtom, false)
  })

  socket.on("success", async (postId: string) => {
    set(qnaAtom, [{ question: DEFAULT_QUESTION, answer: [] }])
    set(currPageAtom, 0)
    set(pageCountAtom, INITIAL_PAGE_COUNT)
    await set(settingsAtom, settings)
    set(loadingAtom, false)

    router.navigate({
      pathname: "/(details)/my-post",
      params: { id: postId },
    })
    get(queryClientAtom).invalidateQueries({ queryKey: ["my-posts"] })
  })

  socket.on("draft-discarded", async () => {
    set(qnaAtom, [{ question: DEFAULT_QUESTION, answer: [] }])
    set(currPageAtom, 0)
    set(pageCountAtom, INITIAL_PAGE_COUNT)
    await set(settingsAtom, settings)
    set(editedAtom, false)
    set(loadingAtom, false)
    get(queryClientAtom).invalidateQueries({ queryKey: ["my-posts"] })
  })
})

export const forwardCreatePostAtom = atom(null, async (get, set) => {
  const qna = get(qnaAtom)
  const socket = get(createPostSocketAtom)
  const currPage = get(currPageAtom)
  const pageCount = get(pageCountAtom)
  const edited = get(editedAtom)
  const { title, description, images, publicPost, location, distance } = await get(settingsAtom)

  if (!socket) {
    console.warn("[forward] Socket is not initialized!")
    return
  }

  /**
   * Handling special pages (not regular Q&A)
   */
  // If on the last page, submit
  if (currPage === pageCount - 1) {
    if (!title || title.trim() === "") {
      Alert.alert("Title required", "Please enter a title for your post.")
      return
    } else if (description && description.trim() === "") {
      Alert.alert(
        "Description cannot be empty",
        "If you want to add a description, it cannot be empty."
      )
      return
    }
    set(loadingAtom, true)
    const imagesWithFiles: { uri: string; file: Blob; mimeType: string }[] = []
    for (const img of images) {
      const response = await fetch(img.localUri)
      const blob = await response.blob()
      imagesWithFiles.push({ uri: img.localUri, file: blob, mimeType: img.mimeType })
    }
    socket.emit("submit", {
      title,
      description,
      publicPost,
      images: imagesWithFiles,
      location,
      distance,
    })
    return
  } else if (currPage === pageCount - 2) {
    // optional location page
    set(currPageAtom, curr => curr + 1)
    return
  } else if (qna[currPage]?.question.optional) {
    // optional "anything else" page
    set(loadingAtom, true)
    set(editedAtom, false)
    socket.emit("chat", qna)
    return
  }

  // Validate current answer
  if (
    !qna[currPage] ||
    qna[currPage].answer.length === 0 ||
    (qna[currPage].question.type === "short_answer" &&
      qna[currPage].answer[0].length < MINIMUM_SHORT_ANSWER_LENGTH)
  ) {
    return
  }

  // if not changed, do nothing
  if (!edited) {
    set(currPageAtom, curr => curr + 1)
    return
  }

  set(loadingAtom, true)
  set(editedAtom, false)
  // If user went back to change something, we need to get rid of their subsequent QAs
  // If they are just doing next normally, this will have no effect
  const qnaSlice = qna.slice(0, currPage + 1)
  socket.emit("chat", qnaSlice)
})

export const pickImageAtom = atom(null, async (get, set) => {
  const permissionResult = await ImagePicker.requestMediaLibraryPermissionsAsync()

  if (!permissionResult.granted) {
    Alert.alert("Permission required", "Permission to access the media library is required.")
    return
  }

  let result = await ImagePicker.launchImageLibraryAsync({
    mediaTypes: ["images", "videos"],
    allowsMultipleSelection: true,
  })

  const newImages: ImageObject[] = []
  if (!result.canceled && result.assets.length > 0) {
    for (const asset of result.assets) {
      const localUri = asset.uri
      const mimeType = asset.mimeType || "image/jpeg"
      newImages.push({ localUri, mimeType, url: "", key: "" })
    }
    const prevSettings = await get(settingsAtom)
    await set(settingsAtom, { ...prevSettings, images: [...prevSettings.images, ...newImages] })
  }
})

export const discardDraftAtom = atom(null, async (get, set) => {
  const socket = get(createPostSocketAtom)
  if (!socket) return

  Alert.alert("Discard Draft", "Are you sure you want to discard the current draft?", [
    {
      text: "Cancel",
      style: "cancel",
    },
    {
      text: "Discard",
      style: "destructive",
      onPress: () => {
        set(loadingAtom, true)
        socket.emit("discard-draft")
      },
    },
  ])
})

export const getNewQuestionAtom = atom(null, async (get, set) => {
  const socket = get(createPostSocketAtom)
  const qna = get(qnaAtom)
  const currPage = get(currPageAtom)
  if (!socket) return
  if (currPage >= qna.length) return

  {
    Alert.alert("Get New Question", "Are you sure you want to get a different question?", [
      {
        text: "Cancel",
        style: "cancel",
      },
      {
        text: "Redo",
        style: "default",
        onPress: () => {
          if (currPage === 0) {
            // If on the first page, just restart
            set(loadingAtom, true)
            socket.emit("discard-draft")
            return
          } else if (currPage === qna.length + 1) {
            // If on the last page, do nothing
            return
          }

          set(loadingAtom, true)
          const qnaSlice = qna.slice(0, currPage)
          set(currPageAtom, curr => curr - 1)
          socket.emit("chat", qnaSlice)
        },
      },
    ])
  }
})
